function colorOption(color, references, version = "hd1") {
  const option = {
    key: `${color.zh} ${color.en}`,
    label: `${color.zh} ${color.en}`,
    zh: color.zh,
    en: color.en,
    image: `/assets/homogenous/kn-${color.code.slice(3)}.webp?v=${version}`,
  };
  if (references?.length) option.references = references;
  return option;
}

export function homogenousColorGroup() {
  return {
    id: "tile-color",
    label: "顏色",
    labelEn: "Colour",
    keepOrder: true,
    dependsOn: "vinyl-code",
    when: ["Homogeneous Non-Directional (F2)", "Homogeneous Directional (F2d)"],
    options: [
      ...HOMOGENOUS_COLORS.map((color) => colorOption(color)),
      ...VINYL_COLORS_2.map((color) => colorOption(color, VINYL_SCENES)),
      ...VINYL_COLORS_3.map((color) => colorOption(color, VINYL_SCENES_3, "hd2")),
      ...VINYL_COLORS_WOOD.map((color) => colorOption(color, VINYL_SCENES_WOOD, "hd2")),
    ],
  };
}

export function homogenousColorName(option, lang) {
  if (!option || typeof option !== "object") return "";
  if (lang === "zh" && option.zh) return option.zh;
  if (option.en) return option.en;
  return String(option.label || "");
}

export function homogenousColorOption(groups, picked) {
  const group = (groups || []).find((item) => item?.id === "tile-color");
  if (!group) return null;
  const key = String(picked?.["tile-color"] || "");
  if (!key) return null;
  return (group.options || []).find((option) => option?.key === key || option?.label === key) || null;
}
